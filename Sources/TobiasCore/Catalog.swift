import Foundation

public enum ActionKind: String, Codable, Sendable {
    case removeContents
    case command
    case manual
}

public enum Risk: String, Codable, Sendable {
    case regenerates
    case redownloads
}

public struct Target: Codable, Identifiable, Hashable, Sendable {
    public var id: String
    public var label: String
    public var note: String
    public var paths: [String]
    public var action: ActionKind
    public var command: String?
    public var manualCommand: String?
    public var quitApps: [String]
    public var risk: Risk
    /// Set only on targets generated by `CacheDiscovery`; never read from or written to JSON.
    public var discovery: DiscoveryInfo?

    public init(
        id: String, label: String, note: String = "", paths: [String],
        action: ActionKind, command: String? = nil, manualCommand: String? = nil,
        quitApps: [String] = [], risk: Risk = .regenerates, discovery: DiscoveryInfo? = nil
    ) {
        self.id = id
        self.label = label
        self.note = note
        self.paths = paths
        self.action = action
        self.command = command
        self.manualCommand = manualCommand
        self.quitApps = quitApps
        self.risk = risk
        self.discovery = discovery
    }

    enum CodingKeys: String, CodingKey {
        case id, label, note, paths, action, command, manualCommand, quitApps, risk
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        label = try c.decode(String.self, forKey: .label)
        note = try c.decodeIfPresent(String.self, forKey: .note) ?? ""
        paths = try c.decode([String].self, forKey: .paths)
        action = try c.decode(ActionKind.self, forKey: .action)
        command = try c.decodeIfPresent(String.self, forKey: .command)
        manualCommand = try c.decodeIfPresent(String.self, forKey: .manualCommand)
        quitApps = try c.decodeIfPresent([String].self, forKey: .quitApps) ?? []
        risk = try c.decodeIfPresent(Risk.self, forKey: .risk) ?? .regenerates
    }

    /// Existing concrete paths for this target (home expanded, globs resolved).
    public func resolvedPaths(using pathGuard: PathGuard) -> [String] {
        paths.flatMap { Glob.expand(pathGuard.expand($0)) }
    }
}

public struct RejectedTarget: Equatable, Sendable {
    public let id: String
    public let reason: String
}

public struct Catalog: Sendable {
    public var targets: [Target]
    public var rejected: [RejectedTarget]

    public init(targets: [Target], rejected: [RejectedTarget] = []) {
        self.targets = targets
        self.rejected = rejected
    }

    /// SwiftPM's generated `Bundle.module` looks next to the app bundle, which breaks inside a
    /// packaged .app, so look in Contents/Resources first and use `Bundle.module` last
    /// (it is what `swift run` and the tests use).
    static func catalogURL() -> URL? {
        if let url = Bundle.main.url(forResource: "catalog", withExtension: "json") { return url }
        if let resources = Bundle.main.resourceURL,
           let bundle = Bundle(url: resources.appendingPathComponent("tobias_TobiasCore.bundle")),
           let url = bundle.url(forResource: "catalog", withExtension: "json") {
            return url
        }
        return Bundle.module.url(forResource: "catalog", withExtension: "json")
    }

    public static func bundledTargets() throws -> [Target] {
        guard let url = catalogURL() else { throw CocoaError(.fileNoSuchFile) }
        return try JSONDecoder().decode([Target].self, from: Data(contentsOf: url))
    }

    /// Bundled targets, then user targets (same id replaces). Invalid entries are rejected, not fatal.
    public static func load(userFile: URL?, pathGuard: PathGuard) throws -> Catalog {
        var merged: [String: Target] = [:]
        var order: [String] = []
        func add(_ t: Target) {
            if merged[t.id] == nil { order.append(t.id) }
            merged[t.id] = t
        }
        try bundledTargets().forEach(add)

        var rejected: [RejectedTarget] = []
        if let userFile, FileManager.default.fileExists(atPath: userFile.path) {
            do {
                let user = try JSONDecoder().decode([Target].self, from: Data(contentsOf: userFile))
                user.forEach(add)
            } catch {
                rejected.append(RejectedTarget(id: userFile.lastPathComponent, reason: "Could not read: \(error)"))
            }
        }

        var valid: [Target] = []
        for id in order {
            let t = merged[id]!
            if let reason = validate(t, pathGuard: pathGuard) {
                rejected.append(RejectedTarget(id: t.id, reason: reason))
            } else {
                valid.append(t)
            }
        }
        return Catalog(targets: valid, rejected: rejected)
    }

    static func validate(_ t: Target, pathGuard: PathGuard) -> String? {
        if t.id.isEmpty || t.paths.isEmpty { return "Missing id or paths" }
        switch t.action {
        case .command:
            if (t.command ?? "").trimmingCharacters(in: .whitespaces).isEmpty { return "Missing command" }
        case .manual:
            if (t.manualCommand ?? "").trimmingCharacters(in: .whitespaces).isEmpty { return "Missing manualCommand" }
        case .removeContents:
            break
        }
        // Only targets that can delete need to pass the strict check; others are read-only paths.
        if t.action == .removeContents || t.action == .command {
            for p in t.paths {
                do { try pathGuard.validatePattern(p) } catch { return "\(error)" }
            }
        }
        return nil
    }
}
